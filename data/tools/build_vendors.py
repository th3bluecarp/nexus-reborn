# Vendor stock for starting-zone vendors from archived Jabbithole "Sells" tabs.
import json, csv, collections
J='/w/json/'; ld=lambda n: json.load(open(J+n+'.json'))
text={int(k):v for k,v in json.load(open(J+'text.json')).items()}; T=lambda i:(text.get(i) or '')
cr={c['Id']:c for c in ld('Creature2')}; items={i['Id']:i for i in ld('Item2')}
MAPW={'northernwilds':426,'everstargrove':990,'crimsonisle':870,'levianbay':1387,'algoroc':51,'celestion':51,'galeras':51,'thayd':51,'whitevale':51,'deradune':22,'ellevar':22,'auroria':22,'illium':22}
ents=collections.defaultdict(list)
for r in csv.DictReader(open('/w/db/entity.tsv'),delimiter='\t'):
    c=cr.get(int(r['creature']))
    if c and int(r['creature']) not in ents[(int(r['world']),T(c['LocalizedTextIdName']))]: ents[(int(r['world']),T(c['LocalizedTextIdName']))].append(int(r['creature']))
CAT=[('General',235,lambda i:i['Item2FamilyId'] not in (1,2)),('Weapons',484133,lambda i:i['Item2FamilyId']==2),
     ('Light Armor',15120,lambda i:i['Item2FamilyId']==1 and i['Item2CategoryId']==1),('Medium Armor',15119,lambda i:i['Item2FamilyId']==1 and i['Item2CategoryId']==2),
     ('Heavy Armor',15118,lambda i:i['Item2FamilyId']==1 and i['Item2CategoryId']==3)]
sql=['-- Starting-zone vendor stock from archived Jabbithole vendor pages. Generated by tools/build_vendors.py.',
     '-- Vendors are matched by creature id and world, not entity id, because world database entity ids depend on load order.',
     '-- Load after the NexusForever world database files.']
summary=[]
for v in json.load(open('/a/parsed/jh_npcs.json')):
    if not v['sells'] or v['map'] not in MAPW: continue
    w=MAPW[v['map']]; targets=ents.get((w,v['name']),[])
    stock=[items[s['item_id']] for s in v['sells'] if s['item_id'] in items]
    cats=[(name,tid,[i for i in stock if f(i)]) for name,tid,f in CAT]
    cats=[c for c in cats if c[2]]
    for cid in targets:
        E=f'FROM `entity` WHERE `Creature`={cid} AND `World`={w}'
        sql.append(f'-- {v["name"]} (creature {cid}, world {w})')
        for t in ('entity_vendor_item','entity_vendor_category','entity_vendor'):
            sql.append(f'DELETE FROM `{t}` WHERE `id` IN (SELECT `Id` {E});')
        sql.append(f'INSERT INTO `entity_vendor` (`id`,`buyPriceMultiplier`,`sellPriceMultiplier`) SELECT `Id`,1,1 {E};')
        idx=0
        for ci,(name,tid,its) in enumerate(cats):
            sql.append(f'INSERT INTO `entity_vendor_category` (`id`,`index`,`localisedTextId`) SELECT `Id`,{ci},{tid} {E};')
            for it in its:
                sql.append(f'INSERT INTO `entity_vendor_item` (`id`,`index`,`categoryIndex`,`itemId`) SELECT `Id`,{idx},{ci},{it["Id"]} {E};'); idx+=1
    summary.append((v['name'],v['map'],len(stock),len(targets),[c[0] for c in cats]))
open('/a/parsed/starting_zone_vendors.sql','w').write('\n'.join(sql)+'\n')
for s in summary: print(s)
