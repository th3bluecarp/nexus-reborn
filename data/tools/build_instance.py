# Spawns for an instanced map (shiphand mission, expedition) from archived Jabbithole pages on that map.
# Usage: build_instance.py <jabbithole map> <world id> <level> <first entity id> <output sql>
# Every pin cluster of every page on the map becomes a spawn. Heights come from the map's own WorldLocation2 markers (ship decks are
# not terrain), so pins with no marker within 25 m are skipped. Mobs get the instance's level, objects keep level 1.
import json, sys, math, collections, re
mapname, world, level, first, out = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), sys.argv[5]
J='/w/json/'; ld=lambda n: json.load(open(J+n+'.json'))
text={int(k):v for k,v in json.load(open(J+'text.json')).items()}; T=lambda i:(text.get(i) or '')
cr=ld('Creature2')
byname=collections.defaultdict(list)
for c in cr: byname[T(c['LocalizedTextIdName'])].append(c)
dgrp=collections.defaultdict(list)
for e in ld('Creature2DisplayGroupEntry'): dgrp[e['Creature2DisplayGroupId']].append(e)
ogrp=collections.defaultdict(list)
for e in ld('Creature2OutfitGroupEntry'): ogrp[e['Creature2OutfitGroupId']].append(e)
locs=[l for l in ld('WorldLocation2') if l['WorldId']==world]
MAPS=set(mapname.split(','))
pages=[p for p in json.load(open('/a/parsed/jh_npcs.json')) if p.get('map') in MAPS]
SKIP=re.compile(r'veteran|long agro|unused|holdout', re.I)
# things players and events brought along when the pages were captured, and adds a boss summons
NOT_PLACED={"Combat Supply Drop","Crafting Station","Scrap Metal","Settler's Campfire","Mini Vendbot","Vendbot","Settler Mailbox","Engineer - Hostile Invisible - Bruiserbot","Beneficial Invis Unit for fields","First Anniversary Dance-Plosion Device","Spawnling"}
# named bosses and NPCs stand once
SINGLE={"Cyclopean Parasite","Ensign Bardlet","Captain Lairdell's Log","Hive Queen","Marauder Ship","Asteroid","Riptide the Stone Serpent","Irontide the Venom Snake","Engineer Clamp","Terramaw"}
# named NPCs and bosses (quoted nicknames, titles) stand once
NAMED=re.compile(r'^(The |Captain|Major|Pilot|Judge|Agent|Foreman|Colonel|Professor|Doctor|Ensign|Chief|Commander|Lieutenant|Overseer|Warden|Lord|Lady|Queen|King)|"|\u201c')
MAX_PER_PAGE=int(sys.argv[6]) if len(sys.argv)>6 else 25
def pick(name):
    cands=[c for c in byname.get(name,[]) if not SKIP.search(c['Description'] or '')]
    tagged=[c for c in cands if f'{world}' in (c['Description'] or '')]
    return min(tagged or cands, key=lambda c: c['Id']) if (tagged or cands) else None
def clusters(pins, r=2.5):
    cl=[]
    for x,z in pins:
        for c in cl:
            if math.hypot(c['x']-x,c['z']-z)<=r: c['n']+=1; break
        else: cl.append({'x':x,'z':z,'n':1})
    return cl
rows=[]; report=[]; nid=first
for p in pages:
    if p['name'] in NOT_PLACED or p['name'].lower().startswith(("invis","hostile invis","beneficial invis")): continue
    c=pick(p['name'])
    if not c: report.append((p['name'],'no creature')); continue
    placed=0
    cl_all=sorted(clusters(p['pins'], 5.0), key=lambda k:-k['n'])
    single = p['name'] in SINGLE or NAMED.search(p['name'])
    for cl in cl_all[:1 if single else MAX_PER_PAGE]:
        near=sorted(locs, key=lambda l: math.hypot(l['Position0']-cl['x'], l['Position2']-cl['z']))
        if not near or math.hypot(near[0]['Position0']-cl['x'], near[0]['Position2']-cl['z'])>25: continue
        y=near[0]['Position1']; area=near[0]['WorldZoneId']
        groups=sorted(dgrp.get(c['Creature2DisplayGroupId'],[]), key=lambda e:-e['Weight'])
        disp=groups[0]['Creature2DisplayInfoId'] if groups else 0
        og=sorted(ogrp.get(c['Creature2OutfitGroupId'],[]), key=lambda e:-e['Weight'])
        outfit=og[0]['Creature2OutfitInfoId'] if og else 0
        lvl=level if (c['MaxLevel'] or 0)>1 else 1
        rows.append((nid,c['Id'],world,area,round(cl['x'],3),round(y,3),round(cl['z'],3),disp,outfit,c['FactionId'],lvl,p['name']))
        nid+=1; placed+=1
    report.append((p['name'],f'{c["Id"]} placed {placed}'))
with open(out,'w') as f:
    f.write(f'-- Spawns for {mapname} (world {world}) from archived Jabbithole pins, heights from the map markers. Generated by wildstar-archive/tools/build_instance.py.\n')
    f.write(f'DELETE FROM `entity_stats` WHERE `Id` BETWEEN {first} AND {first+9999};\nDELETE FROM `entity` WHERE `Id` BETWEEN {first} AND {first+9999};\n')
    for (i,cid,w,area,x,y,z,disp,outfit,fac,lvl,name) in rows:
        f.write(f'-- {name}\n')
        f.write(f"INSERT INTO `entity` (`Id`,`Type`,`Creature`,`World`,`Area`,`X`,`Y`,`Z`,`RX`,`RY`,`RZ`,`DisplayInfo`,`OutfitInfo`,`Faction1`,`Faction2`) VALUES ({i},0,{cid},{w},{area},{x},{y},{z},0,0,0,{disp},{outfit},{fac},{fac});\n")
        f.write(f"INSERT INTO `entity_stats` (`Id`,`Stat`,`Value`) VALUES ({i},10,{lvl}),({i},15,0);\n")
for r in report: print(*r)
print('spawns', len(rows))
